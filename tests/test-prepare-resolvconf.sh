#!/usr/bin/env bash
set -euo pipefail

project_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
helper="${project_dir}/amnezia_client/rootfs/usr/local/bin/prepare-resolvconf"
test_dir="$(mktemp -d)"
trap 'rm -rf "${test_dir}"' EXIT

cat > "${test_dir}/fake-resolvconf" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
printf '%s\n' "$*" >> "${RESOLVCONF_TEST_LOG}"
if [[ "${1:-}" == "-u" ]]; then
    printf '# Generated by resolvconf\n' > "${RESOLV_CONF}"
else
    cat > "${RESOLVCONF_TEST_INPUT}"
fi
EOF
chmod +x "${test_dir}/fake-resolvconf"

export RESOLV_CONF="${test_dir}/resolv.conf"
export RESOLVCONF_SNAPSHOT="${test_dir}/snapshot"
export RESOLVCONF_COMMAND="${test_dir}/fake-resolvconf"
export RESOLVCONF_TEST_LOG="${test_dir}/calls"
export RESOLVCONF_TEST_INPUT="${test_dir}/input"

cat > "${test_dir}/without-dns.conf" <<'EOF'
[Interface]
Address = 10.8.1.8/32
EOF
printf 'nameserver 172.30.32.3\n' > "${RESOLV_CONF}"
"${helper}" "${test_dir}/without-dns.conf"
[[ ! -e "${RESOLVCONF_TEST_LOG}" ]]

cat > "${test_dir}/with-dns.conf" <<'EOF'
[Interface]
DNS = 1.1.1.1
EOF
"${helper}" "${test_dir}/with-dns.conf"
grep -Fxq -- '-u' "${RESOLVCONF_TEST_LOG}"
grep -Fxq -- '-a system' "${RESOLVCONF_TEST_LOG}"
grep -Fxq 'nameserver 172.30.32.3' "${RESOLVCONF_SNAPSHOT}"
grep -Fxq 'nameserver 172.30.32.3' "${RESOLVCONF_TEST_INPUT}"

: > "${RESOLVCONF_TEST_LOG}"
"${helper}" "${test_dir}/with-dns.conf"
[[ ! -s "${RESOLVCONF_TEST_LOG}" ]]

echo "resolvconf preparation tests passed"
